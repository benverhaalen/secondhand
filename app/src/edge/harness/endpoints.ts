// Every verb as a documented endpoint (Nate, product/words.md 2026-11-14: "well documented endpoints ... like /write-listing
// with the listing then provided from the app"). The list and its doc are generated from the platform profiles and the
// adapters' manifests, so they cannot drift: endpoints.test.ts fails when ENDPOINTS.md differs from what this writes.
// Regenerate: node app/src/edge/harness/endpoints.ts --write
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PROFILES } from './platform.ts';
import { SITES, VERBS, isWrite, type Manifest, type Site, type Verb } from './protocol.ts';

// The path each verb answers on; agent proposal names, the verb stays the canon name.
export const PATHS: Record<Verb, string> = {
  post: '/write-listing', revise: '/edit-listing', end: '/end-listing', relist: '/relist', read_listings: '/listings',
  read_inbox: '/inbox', send_message: '/send-message', read_offers: '/offers', answer_offer: '/answer-offer', make_offer: '/make-offer',
  read_orders: '/orders', read_stats: '/stats', read_storefront: '/storefront', search: '/search', save: '/save',
};

const SAYS: Record<Verb, string> = {
  post: 'Puts a new listing up, from the listing the app sends.', revise: 'Changes a live listing in place.', end: 'Takes a listing down.',
  relist: 'Puts an ended listing back up as a new listing.', read_listings: 'Reads the account\'s listings and their state.',
  read_inbox: 'Reads message threads.', send_message: 'Sends a message in a thread.', read_offers: 'Reads open offers.',
  answer_offer: 'Accepts, counters or declines an offer.', make_offer: 'Sends an offer to a buyer or a seller.',
  read_orders: 'Reads sales and orders.', read_stats: 'Reads per-listing figures.', read_storefront: "Reads the shop's own figures: followers, rating, totals.", search: 'Searches the market.', save: 'Saves or likes a listing.',
};

export type Endpoint = { site: Site; verb: Verb; path: string; method: 'GET' | 'POST'; write: boolean; available: true | string;
  session: 'signed_in' | 'public' | 'unknown'; input: Record<string, string>; output: Record<string, string> };

export function endpoints(manifests: Manifest[] = []): Endpoint[] {
  return SITES.flatMap(site => VERBS.map(verb => {
    const m = manifests.find(x => x.site === site && x.verb === verb), has = PROFILES[site].verbs[verb];
    return { site, verb, path: `/${site}${PATHS[verb]}`, method: isWrite(verb) ? 'POST' as const : 'GET' as const, write: isWrite(verb),
      available: has === true ? true : has.absent, session: m?.session ?? 'unknown', input: m?.input_schema ?? {}, output: m?.output_schema ?? {} };
  }));
}

export function endpointDoc(manifests: Manifest[] = []): string {
  const rows = endpoints(manifests);
  const out = ['# Harness endpoints', '', 'Generated by `node app/src/edge/harness/endpoints.ts --write` from the platform profiles (platform.ts) and the adapters\' manifests. Do not edit by hand.', '',
    'Every endpoint is `harness.call(site, verb, args)` and answers the one envelope in protocol.ts. A write carries `operation_id` and is never replayed. A verb a site lacks answers `no_route` with the reason given here.', ''];
  for (const verb of VERBS) {
    out.push(`## ${PATHS[verb]} (\`${verb}\`)`, '', SAYS[verb], '', '| site | endpoint | method | available | session |', '|---|---|---|---|---|');
    for (const e of rows.filter(r => r.verb === verb)) out.push(`| ${e.site} | \`${e.path}\` | ${e.method} | ${e.available === true ? 'yes' : `no: ${e.available}`} | ${e.session} |`);
    out.push('');
  }
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1] && process.argv.includes('--write'))
  writeFileSync(new URL('./ENDPOINTS.md', import.meta.url), endpointDoc());
