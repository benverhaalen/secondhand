#!/usr/bin/env node
// Turns brand/tokens.css into the values React Native can read, which has no CSS variables.
// node scripts/tokens-to-ts.mjs          writes app/src/ui/tokens.generated.ts
// The repo check fails when that file is not what this prints (.agents/checks/parts.mjs).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT = 'app/src/ui/tokens.generated.ts';
const camel = s => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const block = (css, open) => { const i = css.indexOf(open); return i < 0 ? '' : css.slice(i, css.indexOf('\n}', i)); };
const vars = text => [...text.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)].map(m => [m[1], m[2].trim()]);
// CSS "rgb(10 10 10 / .65)" is "rgba(10, 10, 10, 0.65)" in React Native.
const color = v => {
  if (/^#[0-9a-fA-F]{3,8}$/.test(v)) return v;
  const m = v.match(/^rgb\((\d+) (\d+) (\d+) \/ (\.?\d*\.?\d+)\)$/);
  return m ? `rgba(${m[1]}, ${m[2]}, ${m[3]}, ${Number(m[4])})` : null;
};
const px = v => (/^-?\d*\.?\d+px$/.test(v) ? Number(v.slice(0, -2)) : null);
const ms = v => (/^\d+ms$/.test(v) ? Number(v.slice(0, -2)) : null);
const obj = (name, pairs) => `export const ${name} = {\n${pairs.map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')}\n} as const;\n`;

export function tokensTs(css) {
  const light = vars(block(css, ':root {')), dark = vars(block(css, ':root[data-theme="dark"]'));
  // A color that names another token, "--field-need-1: var(--marigold)", takes that token's value, read in its own mode first.
  const lightMap = new Map(light), darkMap = new Map(dark);
  const resolve = (v, map, depth = 0) => { const m = v.match(/^var\(--([\w-]+)\)$/); if (!m || depth > 4) return v; const next = map.get(m[1]) ?? lightMap.get(m[1]); return next == null ? v : resolve(next, map, depth + 1); };
  const colors = (list, map) => list.map(([k, v]) => [camel(k), color(resolve(v, map))]).filter(([, v]) => v);
  const pick = (re, parse, name = k => k) => light.filter(([k]) => re.test(k)).map(([k, v]) => [camel(name(k)), parse(v)]).filter(([, v]) => v !== null);
  const sizes = Object.fromEntries(light.filter(([k]) => /^t-\d+$/.test(k)).map(([k, v]) => [k.slice(2), px(v)]));
  const lines = Object.fromEntries(light.filter(([k]) => /^lh-\d+$/.test(k)).map(([k, v]) => [k.slice(3), Number(v)]));
  // Tracking is in em in CSS and in points in React Native: -0.015em at 36 is -0.54.
  const tracks = Object.fromEntries(light.filter(([k]) => /^tr-\d+$/.test(k)).map(([k, v]) => [k.slice(3), parseFloat(v)]));
  const type = Object.keys(sizes).map(n => [`t${n}`, { fontSize: sizes[n], lineHeight: Math.round(sizes[n] * (lines[n] ?? 1.3)), ...(tracks[n] ? { letterSpacing: Math.round(sizes[n] * tracks[n] * 100) / 100 } : {}) }]);
  return [
    '// @generated by scripts/tokens-to-ts.mjs from brand/tokens.css. Change the CSS, then run the script.\n',
    obj('color', colors(light, lightMap)),
    obj('colorDark', colors(dark, darkMap)),
    obj('space', pick(/^(s-\d+|gutter)$/, px, k => k.replace('s-', 's'))),
    obj('radius', pick(/^r-/, px, k => k.slice(2))),
    obj('size', pick(/^(control-min|button-h|nav-h|tab-h|photo-card|card-corner|card-pad|card-decision-h|card-item-h|notice-h|pill-card-h|pill-card-pad|tag-h|tag-icon|badge-h|site-badge|wash-h)$/, px)),
    obj('type', type),
    // The first face of each stack is the brand's; the rest is the fallback the platform picks from.
    obj('font', pick(/^font-(text|display)$/, v => v.match(/^"([^"]+)"/)?.[1] ?? null, k => k.slice(5))),
    obj('weight', pick(/^w-(text|display)$/, v => (/^\d{3}$/.test(v) ? v : null), k => k.slice(2))),
    obj('nudge', pick(/^nudge-display$/, v => (/^\.?\d*\.?\d+em$/.test(v) ? parseFloat(v) : null), () => 'display')),
    obj('calm', pick(/^field-calm-max$/, v => (/^\d+%$/.test(v) ? Number(v.slice(0, -1)) / 100 : null), () => 'max')),
    obj('motion', pick(/^t-(feedback|select|panel)$/, ms, k => k.slice(2))),
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  writeFileSync(root + OUT, tokensTs(readFileSync(root + 'brand/tokens.css', 'utf8')));
  console.log(`wrote ${OUT}`);
}
