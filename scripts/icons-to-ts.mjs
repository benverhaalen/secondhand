#!/usr/bin/env node
// Writes icons.generated.ts: the Hugeicons Stroke Rounded icons the app uses, from the free package (MIT, Hugeicons).
// Art. 10.1: one icon set, Hugeicons Stroke Rounded. The package is not an app dependency; this script reads an unpacked copy.
//   npm pack @hugeicons/core-free-icons && tar xzf hugeicons-core-free-icons-*.tgz
//   node scripts/icons-to-ts.mjs <path to package/dist/cjs>
// To add an icon: put its kebab name (Hugeicons' own, as on hugeicons.com) in NAMES and run the script again.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const NAMES = [
  // tabs and the nav
  'home-01', 'tag-01', 'add-01', 'search-01', 'user', 'inbox',
  // states (constitution Art. 5, States: every state carries its icon)
  'waving-hand-01', 'live-streaming-02', 'money-03', 'package', 'tick-02', 'alert-02', 'pencil-edit-02', 'clock-01', 'hourglass', 'fire',
  // controls
  'more-horizontal', 'cancel-01', 'arrow-left-01', 'arrow-right-01', 'arrow-down-01', 'share-08', 'undo-02', 'refresh', 'edit-02',
  'sorting-01', 'filter-horizontal', 'settings-01',
  // things a card or a page names
  'printer', 'location-01', 'camera-01', 'image-01', 'store-01', 'bubble-chat', 'delivery-truck-01', 'credit-card', 'calendar-03',
  'notification-01', 'information-circle', 'checkmark-circle-02', 'link-01', 'star',
];
const pascal = n => n.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join('') + 'Icon';
const KEEP = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'x2', 'y1', 'y2', 'width', 'height', 'points', 'fill', 'fillRule', 'clipRule']);

const dir = process.argv[2];
if (!dir) { process.stderr.write('usage: node scripts/icons-to-ts.mjs <package/dist/cjs>\n'); process.exit(1); }
const req = createRequire(join(dir, 'x.js'));
const out = {};
for (const n of NAMES) {
  const data = req('./' + pascal(n) + '.js');
  out[n] = data.map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).filter(([k, v]) => KEEP.has(k) && !(k === 'fill' && v === 'none')))]);
}
const body = Object.entries(out).map(([n, shapes]) => `  ${JSON.stringify(n)}: ${JSON.stringify(shapes)},`).join('\n');
const file = fileURLToPath(new URL('../app/src/ui/icons.generated.ts', import.meta.url));
writeFileSync(file, '// @generated by scripts/icons-to-ts.mjs from @hugeicons/core-free-icons (MIT, copyright Hugeicons). Add a name there, never here.\n' +
  'export type Shape = readonly [string, Readonly<Record<string, string>>];\n' +
  `export const ICONS = {\n${body}\n} as const satisfies Record<string, readonly Shape[]>;\n\nexport type IconName = keyof typeof ICONS;\n`);
process.stdout.write(`wrote ${Object.keys(out).length} icons\n`);
