// The code rules a script can check. The ones that need judgment are in .agents/skills/build/SKILL.md.
// Errors: a file named for nothing, a type check switched off, a broad handler that drops the error, conversation history in a comment, a test switched off.
// Warnings are guesses from the text, there to make you look: a long file you changed, and changed code that has no test.
// Not caught, so the review still has to look: Swift try?, pytest xfail, an error caught and then ignored further down, and any written as JSX text.
import { read, err, warn, lineOf, isProductCode, isTest, withoutStrings, commentsOnly } from './util.mjs';

const JS = /\.(tsx?|jsx?|mjs|cjs)$/, TS = /\.tsx?$/, PY = /\.py$/, SWIFT = /\.swift$/;
const LONG = 400;
const NOTHING = /^(?:.*[-_])?(?:utils?|utilities|helpers?|misc)(?:[-_].*)?$/i;
const grabBag = f => f.split('/').some(part => { const stem = part.split('.')[0]; return NOTHING.test(stem) || /[a-z](?:Utils?|Helpers?)$/.test(stem); });
const generated = (f, text) => /\.(types|generated|gen)\.[a-z]+$/.test(f) || /@generated|\bgenerated by\b/i.test(text.split('\n', 5).join('\n'));
// A Maestro flow is a test too, though it is not code.
const proves = f => isTest(f) || /(^|\/)(e2e|\.maestro)\/.*\.ya?ml$/.test(f);
const stem = f => f.split('/').at(-1).split('.')[0].toLowerCase();

const anyType = m => `${m} switches the type check off: name the real type, or use unknown and narrow it where the value enters`;
const SWALLOWED = 'an error is swallowed: handle it, log it with log.error, or let it fail';
const SILENT = 'an error is handled but not logged: call log.error(where, error) so the failure can be replayed';
// The text inside the bracket that opens at `at`, or null if it never closes.
const inside = (t, at) => { const close = { '(': ')', '{': '}' }[t[at]]; let d = 0; for (let i = at; i < t.length; i++) { if (t[i] === t[at]) d++; else if (t[i] === close && --d === 0) return t.slice(at + 1, i); } return null; };
const OFF = 'a test is switched off: fix it, or skip it on a condition that names the reason';
const NOTHING_VALUE = String.raw`(?:null|undefined|void 0|false|true|\[\]|\{\s*\}|0)`;

// [files, the view of the file to read, what to find, what to say]
const RULES = [
  [TS, 'code', /\bas\s+any\b|[:<,|&]\s*any\b(?![\w$.(])|\btype\s+\w+(?:<[^>]*>)?\s*=\s*any\b/g, anyType],
  [TS, 'code', /\bas\s+unknown\s+as\b/g, () => 'as unknown as forces a type the compiler rejected: check the value where it enters and return the real type'],
  [JS, 'comments', /@ts-(?:ignore|nocheck)\b/g, m => `${m} hides a type error: fix the type, or use @ts-expect-error with the reason`],
  [JS, 'comments', /eslint-disable(?:-next-line|-line)?(?=[ \t]*(?:\*\/|$))/gm, m => `${m} with no rule named turns every lint rule off: name the rule and the reason`],
  [PY, 'comments', /#\s*type:\s*ignore(?!\[)/g, () => 'type: ignore with no error code hides every type error on the line: name the code, as in type: ignore[attr-defined]'],
  [JS, 'code', new RegExp(String.raw`\bcatch\s*(?:\([^)]*\))?\s*\{\s*(?:return(?:\s+${NOTHING_VALUE})?\s*;?\s*)?\}`, 'g'), () => SWALLOWED],
  [JS, 'code', new RegExp(String.raw`\.catch\(\s*(?:noop|(?:async\s*)?(?:\([^)]*\)|\w+)\s*=>\s*${NOTHING_VALUE})\s*\)`, 'g'), () => SWALLOWED],
  // A narrow handler (except FileNotFoundError: pass) says which failure is fine. A bare or Exception handler that drops the error does not.
  [PY, 'code', /\bexcept(?:[ \t]+(?:Base)?Exception(?:[ \t]+as[ \t]+\w+)?)?[ \t]*:[ \t]*(?:\n[ \t]*)?(?:pass|\.\.\.|continue|return(?:[ \t]+None)?)[ \t]*$/gm, () => SWALLOWED],
  [SWIFT, 'code', /\bcatch\s*(?:let\s+\w+|_)?\s*\{\s*\}/g, () => 'an error is swallowed: handle it, pass it to JS to log, or let it throw'],
  [/./, 'comments', /\bas (?:we )?discussed\b|\bper (?:the |your )?(?:review|feedback)\b|\bper your (?:request|comments?)\b|\b(?:Ben|Nate|you) (?:asked|wanted|said|suggested)\b|\bas you (?:asked|requested|said|suggested)\b|\bfixed (?:the |a )?bug\b|\bused to be\b/gi,
    m => `"${m}" is conversation or history: a comment says what the code does now and why; the rest belongs in the commit message`],
];
const TEST_RULES = [
  // test.skip(condition, 'reason') is a skip on a named condition, so a first argument that is not a title passes.
  [JS, /(?<![\w.$])(?:it|test|describe)(?:\.\w+)*?\.(?:only\b|fixme\b|skip\b(?!\s*\(\s*[^\s'"`)]))/g],
  [JS, /(?<![\w.$])(?:xit|xtest|xdescribe|fit|fdescribe)\s*\(\s*['"`]/g],
  [JS, /\bskip\s*:\s*true\b/g],
  [PY, /(?<![\w.])(?:pytest\.mark\.skip|unittest\.skip|@skip)\b/g],
  [SWIFT, /@(?:Test|Suite)\s*\([^)\n]*\.disabled\b/g],
];

export function code(root, { files, changed = [] }) {
  const out = [], seen = new Set();
  const add = (where, msg) => { if (!seen.has(where + msg)) { seen.add(where + msg); out.push(err(where, msg)); } };
  const text = f => (read(root, f) ?? '').replace(/\r\n/g, '\n');
  for (const f of files) {
    if (isTest(f) && !/^\.agents\/checks\/|(^|\/)node_modules\//.test(f)) {
      const bare = withoutStrings(f, text(f));
      for (const [ext, re] of TEST_RULES) if (ext.test(f)) for (const m of bare.matchAll(re)) add(`${f}:${lineOf(bare, m.index)}`, OFF);
    }
    if (!isProductCode(f)) continue;
    if (grabBag(f)) add(f, 'name the file for the one idea it owns (listing/price/floor.ts), so a search finds it; utils, helpers and misc say nothing');
    const raw = text(f), views = { code: withoutStrings(f, raw), comments: commentsOnly(f, raw) };
    for (const [ext, view, re, say] of RULES) if (ext.test(f)) for (const m of views[view].matchAll(re)) add(`${f}:${lineOf(views[view], m.index)}`, say(m[0].trim()));
    // In screens and parts, a catch that does something but never logs or rethrows hides the failure from the log (the empty ones are above).
    if (TS.test(f) && /^app\/src\/(app|ui)\//.test(f)) {
      const bare = views.code;
      const flag = (i, body) => { if (body != null && body.trim() && !/\blog\??\.|\bthrow\b/.test(body) && !new RegExp(`^(?:\\([^)]*\\)|\\w+)\\s*=>\\s*${NOTHING_VALUE}$`).test(body.trim())) add(`${f}:${lineOf(bare, i)}`, SILENT); };
      for (const m of bare.matchAll(/\bcatch\s*(?:\([^)]*\))?\s*\{/g)) flag(m.index, inside(bare, m.index + m[0].length - 1));
      for (const m of bare.matchAll(/\.catch\(/g)) flag(m.index, inside(bare, m.index + m[0].length - 1));
    }
    const lines = raw.split('\n').length - (raw.endsWith('\n') ? 1 : 0);
    if (lines > LONG && changed.includes(f) && !generated(f, raw)) out.push(warn(f, `${lines} lines: does this file own more than one idea? (${LONG} is a guess at where to look, not a limit)`));
  }
  const tests = files.filter(proves);
  const untested = changed.filter(f => files.includes(f) && isProductCode(f) && !tests.some(t => stem(t).includes(stem(f))));
  if (untested.length && !changed.some(f => proves(f) && files.includes(f)))
    out.push(warn(untested[0], `${untested[0]}${untested.length > 1 ? ` and ${untested.length - 1} more` : ''} has no test and no test changed: write the failing test first, or say in the commit why a fast test would cost more than the change`));
  return out;
}
