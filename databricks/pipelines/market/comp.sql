CREATE OR REFRESH STREAMING TABLE comp (
  row_id STRING COMMENT 'Frozen source row id, also exposed as comp_id.',
  data STRING COMMENT 'Writer provenance: dataset:<source> (spec/product.md section 3).',
  source STRING COMMENT 'Frozen dataset name used to join its manifest.',
  licence STRING COMMENT 'Source licence as recorded by the extractor or manifest.',
  site STRING,
  url STRING,
  kind STRING,
  product_id STRING,
  family_id STRING COMMENT 'Source product family, when available.',
  cluster_id STRING COMMENT 'Source grouping of related listings, when available.',
  brand STRING,
  category STRING,
  condition STRING,
  size STRING,
  era STRING COMMENT 'Product era used by the valuation product spec.',
  title STRING,
  photo_count BIGINT,
  seller_feedback BIGINT,
  price_type STRING COMMENT 'sold, asking or ended_unsold; unsold prices are not sale outcomes.',
  price_cents BIGINT,
  buyer_shipping_cents BIGINT,
  listed_at TIMESTAMP,
  at TIMESTAMP COMMENT 'Source observation or outcome time; undated rows stay null.',
  best_offer BOOLEAN COMMENT 'Whether the source listing allowed a best offer.',
  views BIGINT,
  watchers BIGINT,
  may_model BOOLEAN COMMENT 'Row modelling permission; empty source cells fall back to the manifest.',
  at_ask BOOLEAN COMMENT 'Whether the outcome was at the asking price, if known.',
  priced_from_our_number BOOLEAN COMMENT 'Whether our estimate influenced the price; used to avoid feedback.',
  description STRING,
  retail_cents BIGINT,
  released_at TIMESTAMP,
  region STRING,
  comp_id STRING COMMENT 'row_id in the comp shape read by valuation/fit.py.',
  url_ref STRING COMMENT 'Source URL in the comp shape read by valuation/fit.py.',
  sold_at TIMESTAMP COMMENT 'Outcome time only for sold rows.',
  observed_at TIMESTAMP COMMENT 'Source time, not ingestion time.',
  lot_parts ARRAY<STRING> COMMENT 'Empty: these frozen rows describe single products.',
  source_sha256 STRING COMMENT 'Manifest output.sha256, the frozen decompressed CSV hash.',
  extractor_version STRING COMMENT 'Manifest code_commit used to extract the source.',
  source_file STRING COMMENT 'Landing CSV path reported by file metadata.',
  ingested_at TIMESTAMP COMMENT 'Time bronze ingested this row.',
  may_store BOOLEAN COMMENT 'Agent proposal: public contest and research rows may be stored.',
  may_show BOOLEAN COMMENT 'Agent proposal: public contest and research rows may be shown.',
  may_share BOOLEAN COMMENT 'Agent proposal: public contest and research rows are never re-shared.',
  CONSTRAINT known_data EXPECT (data IS NOT NULL) ON VIOLATION FAIL UPDATE,
  CONSTRAINT positive_price EXPECT (price_cents > 0) ON VIOLATION DROP ROW,
  CONSTRAINT known_price_type EXPECT (price_type IN ('sold', 'asking', 'ended_unsold')) ON VIOLATION DROP ROW,
  CONSTRAINT known_model_rights EXPECT (may_model IS NOT NULL) ON VIOLATION FAIL UPDATE,
  CONSTRAINT known_row EXPECT (row_id IS NOT NULL) ON VIOLATION FAIL UPDATE,
  CONSTRAINT known_manifest EXPECT (source_sha256 IS NOT NULL) ON VIOLATION FAIL UPDATE
)
COMMENT 'Typed public market comps with source evidence and rights (spec/databricks-build.md §3, §7).'
AS SELECT
  r.row_id, concat('dataset:', r.source) AS data, r.source, coalesce(NULLIF(r.licence, ''), m.licence) AS licence,
  r.site, r.url, r.kind, r.product_id, r.family_id, r.cluster_id,
  r.brand, r.category, r.condition, r.size, r.era, r.title,
  CAST(NULLIF(r.photo_count, '') AS BIGINT) AS photo_count,
  CAST(NULLIF(r.seller_feedback, '') AS BIGINT) AS seller_feedback,
  r.price_type,
  CAST(NULLIF(r.price_cents, '') AS BIGINT) AS price_cents,
  CAST(NULLIF(r.buyer_shipping_cents, '') AS BIGINT) AS buyer_shipping_cents,
  CAST(NULLIF(r.listed_at, '') AS TIMESTAMP) AS listed_at,
  CAST(NULLIF(r.at, '') AS TIMESTAMP) AS at,
  CASE r.best_offer WHEN 'True' THEN true WHEN 'False' THEN false END AS best_offer,
  CAST(NULLIF(r.views, '') AS BIGINT) AS views,
  CAST(NULLIF(r.watchers, '') AS BIGINT) AS watchers,
  coalesce(CASE r.may_model WHEN 'True' THEN true WHEN 'False' THEN false END, m.may_model) AS may_model,
  CASE r.at_ask WHEN 'True' THEN true WHEN 'False' THEN false END AS at_ask,
  CASE r.priced_from_our_number WHEN 'True' THEN true WHEN 'False' THEN false END AS priced_from_our_number,
  r.description,
  CAST(NULLIF(r.retail_cents, '') AS BIGINT) AS retail_cents,
  CAST(NULLIF(r.released_at, '') AS TIMESTAMP) AS released_at,
  r.region,
  r.row_id AS comp_id, r.url AS url_ref,
  CASE WHEN r.price_type = 'sold' THEN CAST(NULLIF(r.at, '') AS TIMESTAMP) END AS sold_at,
  CAST(NULLIF(r.at, '') AS TIMESTAMP) AS observed_at,
  CAST(array() AS ARRAY<STRING>) AS lot_parts,
  m.source_sha256, m.extractor_version, r.source_file, r.ingested_at,
  true AS may_store, true AS may_show, false AS may_share
FROM STREAM(sold_raw) r
LEFT JOIN source_manifest m ON r.source = m.source;
